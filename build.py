def render_items(items) -> str:
    out = []
    for it in items:
        if isinstance(it, str):
            out.append(f"<p>{esc(it)}</p>")
        elif it[0] == "list":
            out.append("<ul>" + "".join(f"<li>{esc(x)}</li>" for x in it[1]) + "</ul>")
        elif it[0] == "table":
            head = "".join(f"<th>{esc(h)}</th>" for h in it[1])
            rows = "".join("<tr>" + "".join(f"<td>{esc(c)}</td>" for c in r) + "</tr>" for r in it[2])
            out.append(f"<table><tr>{head}</tr>{rows}</table>")
    return "".join(out)


